export type Language = "es" | "en";
export type LanguagePref = Language | "system";

const dicts: Record<Language, Dict> = { es, en };
const PREF_KEY = "vexcast.language";

export function deviceLanguage(): Language {
  try {
    const code = getLocales()[0]?.languageCode?.toLowerCase();
    return code === "en" ? "en" : "es";
  } catch {
    return "es";
  }
}

export type TFunction = (key: TKey, vars?: Record<string, string | number>) => string;

function translate(lang: Language, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[lang][key] ?? es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

interface I18nValue {
  lang: Language;
  pref: LanguagePref;
  /** BCP-47 tag for Intl formatting. */
  locale: string;
  setPref: (p: LanguagePref) => void;
  t: TFunction;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [pref, setPrefState] = useState<LanguagePref>("system");

  useEffect(() => {
    getJSON<LanguagePref>(PREF_KEY, "system").then(setPrefState);
  }, []);

  const setPref = useCallback((p: LanguagePref) => {
    setPrefState(p);
    void setJSON(PREF_KEY, p);
  }, []);

  const lang: Language = pref === "system" ? deviceLanguage() : pref;
  const value = useMemo<I18nValue>(
    () => ({
      lang,
      pref,
      locale: lang === "es" ? "es-ES" : "en-US",
      setPref,
      t: (key, vars) => translate(lang, key, vars),
    }),
    [lang, pref, setPref],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const v = useContext(I18nContext);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}

export function useT(): TFunction {
  return useI18n().t;
}
